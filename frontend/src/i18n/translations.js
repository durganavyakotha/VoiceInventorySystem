export function normalizeLang(code) {
  if (!code) return 'en';
  const c = String(code).toLowerCase();
  if (c.startsWith('te') || c.includes('telugu')) return 'te';
  if (c.startsWith('hi') || c.includes('hindi')) return 'hi';
  if (c.startsWith('ta') || c.includes('tamil')) return 'ta';
  if (c.startsWith('kn') || c.includes('kannada')) return 'kn';
  return 'en';
}

export function t(key, lang = 'en') {
  const l = normalizeLang(lang);
  return translations[l]?.[key] || translations.en[key] || key;
}

export default translations;
